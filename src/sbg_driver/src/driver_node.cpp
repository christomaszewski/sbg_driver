using Trigger = std_srvs::srv::Trigger;

constexpr double k_rad_to_deg = 180.0 / 3.14159265358979323846;

// Auto epoch tolerance applied on identified High Performance INS hardware
// (outputs.epoch_tolerance_us = -1): one period of a 100 Hz composed log, so
// the freshest cached log always qualifies at typical EKF output rates while
// a genuinely stale one still gets the honest "orientation unknown" path.
constexpr std::uint32_t k_hpins_epoch_tolerance_us = 10'000;

constexpr std::string_view mag_quality_name(sbg::MagCalibQuality q) noexcept
{
  switch (q) {
    case sbg::MagCalibQuality::Optimal:
      return "optimal";
    case sbg::MagCalibQuality::Good:
      return "good";
    case sbg::MagCalibQuality::Poor:
      return "poor";
    case sbg::MagCalibQuality::Invalid:
      return "invalid";
  }
  return "unknown";
}

constexpr std::string_view mag_confidence_name(sbg::MagCalibConfidence c) noexcept
{
  switch (c) {
    case sbg::MagCalibConfidence::High:
      return "high";
    case sbg::MagCalibConfidence::Medium:
      return "medium";
    case sbg::MagCalibConfidence::Low:
      return "low";
  }
  return "unknown";
}

// Operator-facing one-liner. std_srvs/Trigger's message field is free-form,
// so this changes no interface; it is the only place the device's verdict on
// a calibration reaches the user (sbg_msgs/MagCalib carries the opaque
// 16-byte SBG_ECOM_LOG_MAG_CALIB payload, not compute results).
std::string describe_mag_calib(const sbg::MagCalibResults & r)
{
  return std::format(
    "quality={} confidence={} points={}/{} advanced_status=0x{:04x} "
    "heading_err(mean/std/max)={:.2f}/{:.2f}/{:.2f}deg",
    mag_quality_name(r.quality), mag_confidence_name(r.confidence), r.num_points, r.max_num_points,
    r.advanced_status, static_cast<double>(r.mean_accuracy_rad) * k_rad_to_deg,
    static_cast<double>(r.std_accuracy_rad) * k_rad_to_deg,
    static_cast<double>(r.max_accuracy_rad) * k_rad_to_deg);
}

// health.limits.* spell "unset" as NaN: a ROS double parameter cannot be absent.
std::optional<double> health_limit(double value)
{
  return std::isnan(value) ? std::nullopt : std::optional{value};
}

HealthSettings::GnssFix required_gnss_fix(std::string_view name)
{
  using enum HealthSettings::GnssFix;
  if (name == "none") {
    return None;
  }
  if (name == "rtk_float") {
    return RtkFloat;
  }
  if (name == "rtk_fixed") {
    return RtkFixed;
  }
  return Fix;
}

// Fleet identity is configuration (sbg-up renders health.vehicle_id from
// VEHICLE_ID and health.instance from the sensor config's name). The two
// fallbacks below only serve a node started without that launcher.
std::string resolve_vehicle_id(const std::string & configured)
{
  if (!configured.empty()) {
    return configured;
  }
  // The launcher environment is immutable during the node's lifetime.
  const char * env = std::getenv("VEHICLE_ID");
  return env != nullptr ? std::string{env} : std::string{};
}

std::string fallback_instance(const rclcpp_lifecycle::LifecycleNode & node)
{
  std::string ns = node.get_namespace();
  ns.erase(0, ns.find_first_not_of('/'));
  std::ranges::replace(ns, '/', '_');
  return ns.empty() ? std::string{node.get_name()} : ns;
}

